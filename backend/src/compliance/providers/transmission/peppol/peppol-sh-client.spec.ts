describe('PeppolShApClient — invoice response + bootstrap', () => {
  it('sendInvoiceResponse throws (no ApplicationResponse endpoint in the peppol.sh API)', async () => {
    const client = new PeppolShApClient(CONFIG);
    await expect(
      client.sendInvoiceResponse({
        senderParticipantId: '9930:DE811907980',
        receiverParticipantId: '9957:FR32123456789',
        originalMessageId: 'doc_abc123',
        responseCode: 'AB',
      }),
    ).rejects.toThrow(/does not support sending Peppol Invoice Responses/);
    expect(mockFetch).not.toHaveBeenCalled();
  });

  it('signup POSTs to the public endpoint on the production host and returns the one-time key', async () => {
    mockFetch.mockResolvedValueOnce(
      mockJsonResponse(
        { id: 'acc_123', email: 'a@b.c', status: 'active', api_key: 'ps_test_generated' },
        201,
      ),
    );

    const result = await PeppolShApClient.signup('a@b.c', 'Unit');

    expect(result).toEqual({ accountId: 'acc_123', apiKey: 'ps_test_generated' });
    const [url, opts] = mockFetch.mock.calls[0] as [string, RequestInit];
    expect(url).toBe(`${PEPPOL_SH_PROD_URL}/v1/signup`);
    expect(JSON.parse(opts.body as string)).toEqual({ email: 'a@b.c', name: 'Unit' });
    // Public endpoint — no Authorization header.
    expect((opts.headers as Record<string, string>).Authorization).toBeUndefined();
  });

  it('createCompany POSTs to the sandbox host by default and returns the com_ id', async () => {
    mockFetch.mockResolvedValueOnce(mockJsonResponse({ id: 'com_created', name: 'Unit Co' }, 201));

    const result = await PeppolShApClient.createCompany('ps_test_generated', {
      name: 'Unit Co',
      taxId: 'FR32123456789',
      country: 'FR',
    });

    expect(result).toEqual({ companyId: 'com_created' });
    const [url, opts] = mockFetch.mock.calls[0] as [string, RequestInit];
    expect(url).toBe(`${PEPPOL_SH_SANDBOX_URL}/v1/companies`);
    expect((opts.headers as Record<string, string>).Authorization).toBe('Bearer ps_test_generated');
    expect(JSON.parse(opts.body as string)).toEqual({
      name: 'Unit Co',
      tax_id: 'FR32123456789',
      country: 'FR',
    });
  });
});
