describe('PeppolShApClient.getStatus', () => {
  it.each([
    ['queued', 'QUEUED'],
    ['sending', 'SENT'],
    ['delivered', 'DELIVERED'],
    ['failed', 'FAILED'],
    ['weird', 'UNKNOWN'],
  ])('maps %s → %s', async (raw, expected) => {
    mockFetch.mockResolvedValueOnce(mockJsonResponse({ id: 'doc_abc123', status: raw }));

    const client = new PeppolShApClient(CONFIG);
    const result = await client.getStatus('doc_abc123');

    expect(result.status).toBe(expected);
    expect(result.messageId).toBe('doc_abc123');
  });

  it('includes the required company_id query parameter (verified live: 400 without)', async () => {
    mockFetch.mockResolvedValueOnce(mockJsonResponse({ id: 'doc_abc123', status: 'delivered' }));

    const client = new PeppolShApClient(CONFIG);
    await client.getStatus('doc_abc123');

    const [url] = mockFetch.mock.calls[0] as [string];
    expect(url).toBe(`${PEPPOL_SH_SANDBOX_URL}/v1/documents/doc_abc123?company_id=com_unit_test`);
  });

  it('surfaces the last event message on failed documents', async () => {
    mockFetch.mockResolvedValueOnce(
      mockJsonResponse({
        id: 'doc_bad',
        status: 'failed',
        events: [
          { type: 'queued', message: 'accepted' },
          { type: 'failed', message: 'participant not registered' },
        ],
      }),
    );

    const client = new PeppolShApClient(CONFIG);
    const result = await client.getStatus('doc_bad');

    expect(result.status).toBe('FAILED');
    expect(result.mlrDescription).toBe('participant not registered');
  });
});

