let ublXml: string;

beforeAll(async () => {
  const service = new InvoiceRenderingService();
  ublXml = await service.buildEInvoice(renderData()).exportXml('ubl');
});

const CONFIG = {
  apiKey: 'ps_test_unit_key',
  companyId: 'com_unit_test',
  environment: 'TEST' as const,
};

function sendRequest(overrides: Partial<Parameters<PeppolShApClient['send']>[0]> = {}) {
  return {
    senderParticipantId: '9957:FR32123456789',
    receiverParticipantId: '9930:DE811907980',
    documentTypeId: PEPPOL_DOC_TYPES.INVOICE_UBL,
    processId: PEPPOL_BILLING_PROCESS_ID,
    documentBytes: Buffer.from(ublXml, 'utf-8'),
    idempotencyKey: 'unit-key-1',
    ...overrides,
  };
}

// ---------------------------------------------------------------------------
// ublToPeppolShDocument — UBL → JSON extraction
// ---------------------------------------------------------------------------

describe('ublToPeppolShDocument', () => {
  it('extracts number, dates, currency, parties and lines from our generated UBL', () => {
    const payload = ublToPeppolShDocument(ublXml);

    expect(payload.type).toBe('invoice');
    expect(payload.number).toBe('INV-PSH-001');
    expect(payload.issue_date).toBe('2026-07-01');
    expect(payload.currency).toBe('EUR');

    expect(payload.from).toEqual({ name: 'Seller SAS', tax_id: 'FR32123456789' });
    expect(payload.to).toEqual({ name: 'Buyer GmbH', tax_id: 'DE811907980' });

    expect(payload.lines).toHaveLength(2);
    expect(payload.lines[0]).toMatchObject({
      description: 'Consulting',
      quantity: 10,
      unit_price: 100,
      tax_rate: 19,
    });
    expect(payload.lines[1]).toMatchObject({
      description: 'Licence',
      quantity: 2,
      unit_price: 50,
      tax_rate: 19,
    });
  });

  it('throws a descriptive error when the buyer has no tax ID', async () => {
    const data = renderData();
    data.client.partyIdentifiers = [];
    const xml = await new InvoiceRenderingService().buildEInvoice(data).exportXml('ubl');

    expect(() => ublToPeppolShDocument(xml)).toThrow(/AccountingCustomerParty.*tax ID/);
  });

  it('rejects non-UBL documents', () => {
    expect(() => ublToPeppolShDocument('<CrossIndustryInvoice/>')).toThrow(/unsupported UBL root element/);
  });
});

// ---------------------------------------------------------------------------
// send()
// ---------------------------------------------------------------------------

describe('PeppolShApClient.send', () => {
  it('POSTs the JSON document to {sandbox}/v1/documents with Bearer auth (TEST env)', async () => {
    mockFetch.mockResolvedValueOnce(
      mockJsonResponse({ id: 'doc_abc123', status: 'queued', url: '/v1/documents/doc_abc123' }, 202),
    );

    const client = new PeppolShApClient(CONFIG);
    const result = await client.send(sendRequest());

    expect(result).toEqual({ messageId: 'doc_abc123', status: 'QUEUED' });

    const [url, opts] = mockFetch.mock.calls[0] as [string, RequestInit];
    expect(url).toBe(`${PEPPOL_SH_SANDBOX_URL}/v1/documents`);
    expect(opts.method).toBe('POST');
    expect((opts.headers as Record<string, string>).Authorization).toBe('Bearer ps_test_unit_key');

    const body = JSON.parse(opts.body as string);
    expect(body.company_id).toBe('com_unit_test');
    expect(body.type).toBe('invoice');
    expect(body.number).toBe('INV-PSH-001');
    expect(body.issue_date).toBe('2026-07-01');
    expect(body.currency).toBe('EUR');
    expect(body.from).toEqual({ name: 'Seller SAS', tax_id: 'FR32123456789' });
    // Explicit receiver Peppol ID overrides peppol.sh's tax_id lookup.
    expect(body.to).toEqual({
      name: 'Buyer GmbH',
      tax_id: 'DE811907980',
      peppol_id: '9930:DE811907980',
    });
    expect(body.lines).toHaveLength(2);
    expect(body.idempotency_key).toBe('unit-key-1');
  });

  it('targets api.peppol.sh in PROD environment', async () => {
    mockFetch.mockResolvedValueOnce(mockJsonResponse({ id: 'doc_prod1', status: 'queued' }, 202));

    const client = new PeppolShApClient({ ...CONFIG, environment: 'PROD' });
    await client.send(sendRequest());

    const [url] = mockFetch.mock.calls[0] as [string];
    expect(url).toBe(`${PEPPOL_SH_PROD_URL}/v1/documents`);
  });

  it('omits to.peppol_id when no receiver participant id (tax_id routing)', async () => {
    mockFetch.mockResolvedValueOnce(mockJsonResponse({ id: 'doc_x', status: 'queued' }, 202));

    const client = new PeppolShApClient(CONFIG);
    await client.send(sendRequest({ receiverParticipantId: '' }));

    const body = JSON.parse((mockFetch.mock.calls[0] as [string, RequestInit])[1].body as string);
    expect(body.to.peppol_id).toBeUndefined();
    expect(body.to.tax_id).toBe('DE811907980');
  });

  it('throws with the canonical error envelope on non-2xx (consistent with other channels)', async () => {
    mockFetch.mockResolvedValueOnce(
      mockJsonResponse(
        {
          error: {
            type: 'billing_error',
            code: 'insufficient_credits',
            message: 'Company does not have enough credits',
          },
        },
        402,
      ),
    );

    const client = new PeppolShApClient(CONFIG);
    await expect(client.send(sendRequest())).rejects.toThrow(
      /peppol\.sh send failed: HTTP 402 — insufficient_credits/,
    );
  });
});

